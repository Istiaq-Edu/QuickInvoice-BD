// Regenerates 0030_optional_buyer_company.sql from the function bodies that are
// currently live, changing only the required-field guard. Copying the real text
// instead of retyping it means the new migration cannot drift from the functions
// it supersedes.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const migrationsDir = fileURLToPath(new URL("../supabase/migrations/", import.meta.url))
const read = (name) => readFileSync(`${migrationsDir}${name}`, "utf8")

const lineItemDiscounts = read("0025_line_item_discounts.sql")
const fixLineDiscountRpc = read("0026_fix_line_discount_rpc.sql")

// Every occurrence of the buyer-company guard, in both the single-line and the
// multi-line spelling used across the chain.
const guards = [
  / ?or nullif\(trim\(v_canonical->>'buyerCompanyName'\), ''\) is null/g,
  /\n *or nullif\(trim\(v_canonical->>'buyerCompanyName'\), ''\) is null/g,
]

function stripBuyerCompanyGuard(sql) {
  let result = sql
  for (const guard of guards) result = result.replace(guard, "")
  if (result.includes("buyerCompanyName'), '') is null")) {
    throw new Error("a buyerCompanyName guard survived the rewrite")
  }
  return result
}

// The snapshot is rebuilt from the canonical document, where the key can now be
// absent. coalesce keeps the stored JSON a string rather than null so the list and
// preview read the same way for a company-less invoice.
function coalesceSnapshotCompany(sql) {
  return sql.replaceAll(
    "'companyName', v_canonical->>'buyerCompanyName'",
    "'companyName', coalesce(v_canonical->>'buyerCompanyName', '')",
  )
}

function extractFunction(sql, name) {
  const start = sql.indexOf(`create or replace function public.${name}(`)
  if (start < 0) throw new Error(`${name} not found`)
  const end = sql.indexOf("\n$$;", start)
  if (end < 0) throw new Error(`${name} body not terminated`)
  return sql.slice(start, end + 4)
}

// The overpay guard is applied in migration 0031 rather than here, because it
// reads public.invoice_payments, which 0031 is what creates.
const saveInvoiceDraft = stripBuyerCompanyGuard(
  coalesceSnapshotCompany(extractFunction(lineItemDiscounts, "save_invoice_draft")),
)
const finalizeInvoice = stripBuyerCompanyGuard(
  coalesceSnapshotCompany(extractFunction(lineItemDiscounts, "finalize_invoice")),
)
const updateFinalizedInvoice = stripBuyerCompanyGuard(
  coalesceSnapshotCompany(extractFunction(fixLineDiscountRpc, "update_finalized_invoice")),
)

const header = `-- A buyer company name is no longer required. An invoice is often
-- billed to a person rather than a business, so the buyer's company is optional
-- and the required buyer name carries the "Bill to" heading on its own.
--
-- This migration supersedes the required-field guard in all three write paths
-- (save_invoice_draft, update_finalized_invoice, finalize_invoice). Each function
-- body below is copied verbatim from the migration that last defined it
-- (0025_line_item_discounts.sql and 0026_fix_line_discount_rpc.sql) with a single
-- change: the buyerCompanyName term is removed from the guard, and the stored
-- customer snapshot coalesces the now-optional company to an empty string.
--
-- The buyer name stays required, so a finalized invoice is always addressed to
-- someone, and the seller company name is still required.
--
-- Generated by scripts/generate-optional-buyer-company-migration.mjs. Re-run it if
-- any of these three functions are redefined.
begin;
`

const grants = `revoke all on function public.save_invoice_draft(uuid, bigint, date, date, public.payment_status, public.discount_type, integer, jsonb, jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.save_invoice_draft(uuid, bigint, date, date, public.payment_status, public.discount_type, integer, jsonb, jsonb, jsonb, jsonb) to authenticated;
revoke all on function public.finalize_invoice(uuid, uuid, bigint) from public, anon;
grant execute on function public.finalize_invoice(uuid, uuid, bigint) to authenticated;
revoke all on function public.update_finalized_invoice(uuid, bigint, jsonb, date, date, public.payment_status) from public, anon;
grant execute on function public.update_finalized_invoice(uuid, bigint, jsonb, date, date, public.payment_status) to authenticated;

commit;
`

writeFileSync(
  `${migrationsDir}0030_optional_buyer_company.sql`,
  `${header}\n${saveInvoiceDraft}\n\n${finalizeInvoice}\n\n${updateFinalizedInvoice}\n\n${grants}`,
)
console.log("wrote 0030_optional_buyer_company.sql")
