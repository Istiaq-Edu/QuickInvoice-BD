// Regenerates 0032_block_overpaying_edits.sql from the function bodies that 0030
// established, adding only the guard that refuses an edit which would drop an
// invoice's total below the money already received.
//
// Why a separate migration: the guard reads public.invoice_payments, which 0031
// creates. 0030 therefore cannot contain it, and rewriting 0030 to do so would
// break a database that has already applied it.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const migrationsDir = fileURLToPath(new URL("../supabase/migrations/", import.meta.url))
const read = (name) => readFileSync(`${migrationsDir}${name}`, "utf8")

const optionalBuyerCompany = read("0030_optional_buyer_company.sql")

// The overpay guard has to run after v_total is recomputed from the new line
// items, otherwise it would compare the recorded payments against the OLD total
// and reject a legitimate increase. The anchor is the total assignment, which is
// the last point at which the new figure is known.
const overpayGuard = `  if (select coalesce(sum(amount), 0) from public.invoice_payments where invoice_id = p_invoice_id) > v_total then
    return query select p_invoice_id, v_invoice.version, 'PAYMENTS_EXCEED_NEW_TOTAL'::text;
    return;
  end if;
`

function extractFunction(sql, name) {
  const start = sql.indexOf(`create or replace function public.${name}(`)
  if (start < 0) throw new Error(`${name} not found`)
  const end = sql.indexOf("\n$$;", start)
  if (end < 0) throw new Error(`${name} body not terminated`)
  return sql.slice(start, end + 4)
}

function guardAgainstOverpayingEdits(sql) {
  if (sql.includes("PAYMENTS_EXCEED_NEW_TOTAL")) return sql
  // Files read on Windows carry CRLF, so every anchor below is matched against a
  // LF-normalised copy and the result is written back with the original endings.
  // Matching CRLF text with LF anchors fails silently, which previously made this
  // throw on a function that did have the clause.
  const eol = sql.includes("\r\n") ? "\r\n" : "\n"
  const body = sql.replace(/\r\n/g, "\n")
  const totalAnchor = "  v_total := greatest(0, v_subtotal - v_discount_amount);"
  if (!body.includes(totalAnchor)) throw new Error("total assignment anchor not found")

  // The overpay guard only needs the new total and the ledger, so it sits as soon
  // as the total is known.
  //
  // The derived status and settled_on are NOT re-synced here. Migration 0032 runs
  // before 0034 installs the sync_invoice_settled_state trigger, and an inline
  // re-sync would have to be duplicated into both function bodies to survive that
  // ordering, which is exactly the kind of copy-paste drift this generator exists
  // to avoid. 0034 owns that derivation for every write path instead.
  return body.replace(totalAnchor, `${totalAnchor}\n${overpayGuard}`).replace(/\n/g, eol)
}

const finalizeInvoice = guardAgainstOverpayingEdits(extractFunction(optionalBuyerCompany, "finalize_invoice"))
const updateFinalizedInvoice = guardAgainstOverpayingEdits(extractFunction(optionalBuyerCompany, "update_finalized_invoice"))

const header = `-- Refuses an edit that would push a part-paid invoice into overpayment.
--
-- An invoice with recorded payments can no longer be edited down below the
-- amount already received. Lowering the total would leave amount_paid greater
-- than total_amount, which is a silent accounting error: the list would show a
-- negative balance the seller never agreed to. Instead the write is rejected with
-- PAYMENTS_EXCEED_NEW_TOTAL and the UI explains that the payment must be removed
-- first, which keeps the ledger auditable.
--
-- Raising the total is still allowed, so an understated invoice can be corrected
-- and then settled in full.
--
-- Bodies are copied verbatim from 0030_optional_buyer_company.sql, which
-- established the current definitions, and only the guard is added.
--
-- Generated by scripts/generate-overpay-guard-migration.mjs. Re-run it if either
-- function is redefined.
begin;
`

writeFileSync(
  `${migrationsDir}0032_block_overpaying_edits.sql`,
  `${header}\n${finalizeInvoice}\n\n${updateFinalizedInvoice}\n\nrevoke all on function public.finalize_invoice(uuid, uuid, bigint) from public, anon;
grant execute on function public.finalize_invoice(uuid, uuid, bigint) to authenticated;
revoke all on function public.update_finalized_invoice(uuid, bigint, jsonb, date, date, public.payment_status) from public, anon;
grant execute on function public.update_finalized_invoice(uuid, bigint, jsonb, date, date, public.payment_status) to authenticated;

commit;
`,
)
console.log("wrote 0032_block_overpaying_edits.sql")
